import asyncio
from playwright.async_api import async_playwright
URL="http://127.0.0.1:8765/"
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--no-sandbox"])
        pg = await b.new_page(viewport={"width":1600,"height":1000})
        errs=[]; pg.on("pageerror", lambda e: errs.append(str(e)))
        await pg.goto(URL); await pg.wait_for_timeout(400)
        await pg.click("#w1"); await pg.fill("#f_email","jo@empresa.cat"); await pg.fill("#f_label","Feina"); await pg.fill("#f_pw","secret")
        await pg.click("#save"); await pg.wait_for_timeout(2500)
        await pg.screenshot(path="/tmp/shots/30_tree.png")
        # expand Clients and Acme
        await pg.locator(".tn", has_text="Clients").locator("[data-tw]").click()
        await pg.locator(".tn", has_text="Acme").locator("[data-tw]").click()
        await pg.wait_for_timeout(200)
        await pg.screenshot(path="/tmp/shots/31_tree_open.png")
        await pg.locator(".row").first.drag_to(pg.locator(".tn", has_text="2026").first); await pg.wait_for_timeout(1500)
        print("tree after move:", (await pg.locator(".tn", has_text="2026").first.inner_text()).replace("\n"," "))
        await pg.fill("#fq","p01"); await pg.wait_for_timeout(200)
        await pg.screenshot(path="/tmp/shots/32_tree_search.png")
        await pg.fill("#fq","")
        await pg.locator(".row").first.locator('[data-a="move"]').click(); await pg.wait_for_timeout(300)
        await pg.fill("#pq","reun"); await pg.wait_for_timeout(200)
        await pg.screenshot(path="/tmp/shots/33_picker.png")
        await pg.locator("#ptree .tn", has_text="Reunions").click(); await pg.wait_for_timeout(1200)
        await pg.click('.nav[data-p="carpetes"]'); await pg.wait_for_timeout(700)
        await pg.screenshot(path="/tmp/shots/34_carpetes.png")
        await pg.click("#expall"); await pg.wait_for_timeout(200)
        await pg.screenshot(path="/tmp/shots/35_carpetes_all.png", full_page=True)
        await pg.locator(".mrow", has_text="Bosch").locator('[data-a="sub"]').click()
        await pg.fill("#pv","Pressupostos"); await pg.click(".ov [data-ok]"); await pg.wait_for_timeout(800)
